        self.status = tk.Text(self, height=8, bg="#111", fg="#9cf", relief="flat",
                              font=("Consolas", 9))
        self.status.pack(fill="both", expand=True, padx=14, pady=(8, 0))
        self.log(f"CHARA.BIN: {len(self.bundles)} bundles loaded")
        self.log(f"ISO: {self.iso_path if self.iso_path else '⚠ NOT FOUND — set ISO path in script'}")
